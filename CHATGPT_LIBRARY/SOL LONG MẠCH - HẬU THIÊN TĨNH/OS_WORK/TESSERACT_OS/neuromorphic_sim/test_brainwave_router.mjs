import { createBody, tickBody } from './brainwave_router.mjs';
import assert from 'node:assert/strict';
const sim = (extras = {}) => ({source_kind:'SIMULATED_INPUT',heat_intensity:0.05,touch_pressure:0,obstacle_closeness:0,...extras});
const initial=createBody();
const beta=tickBody(initial,sim());
assert.equal(beta.action,'VIRTUAL_SCAN');
const delta=tickBody(beta.state,sim({next_gate:'DELTA'}));
assert.equal(delta.event.kind,'BRAINWAVE_GATE_TRANSITION');
assert.equal(delta.event.event_id,'SIM_EVT_00000002');
assert.equal(delta.action,'VIRTUAL_SAFE_STOP');
assert.equal(tickBody(delta.state,sim()).action,'VIRTUAL_SAFE_STOP');
const reflex=tickBody(initial,sim({heat_intensity:1,touch_pressure:1,obstacle_closeness:.9,secret:'MUST_NOT_LEAK'}));
assert.equal(reflex.event.kind,'SNN_SPIKE');
assert.equal(reflex.action,'VIRTUAL_WITHDRAW');
assert.ok(!JSON.stringify(reflex).includes('MUST_NOT_LEAK'));
const invalid=tickBody(initial,{source_kind:'EXTERNAL_UNVERIFIED'});
assert.equal(invalid.accepted,false);
assert.equal(invalid.state,initial);
assert.throws(()=>tickBody(initial,sim({heat_intensity:2})),/Invalid normalized/);
assert.throws(()=>tickBody(initial,sim({next_gate:'NOT_A_GATE'})),/Unknown gate/);
console.log('SNN virtual reflex tests passed: 10 assertions');
